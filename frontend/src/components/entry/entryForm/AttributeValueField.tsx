import { FC } from "react";
import { Control } from "react-hook-form";
import { UseFormSetValue } from "react-hook-form";

import { ArrayNumberAttributeValueField } from "./ArrayNumberAttributeValueField";
import { BooleanAttributeValueField } from "./BooleanAttributeValueField";
import { DateAttributeValueField } from "./DateAttributeValueField";
import { DateTimeAttributeValueField } from "./DateTimeAttributeValueField";
import { Schema } from "./EntryFormSchema";
import { GroupAttributeValueField } from "./GroupAttributeValueField";
import { NumberAttributeValueField } from "./NumberAttributeValueField";
import {
  ArrayNamedObjectAttributeValueField,
  NamedObjectAttributeValueField,
  ObjectAttributeValueField,
} from "./ObjectAttributeValueField";
import { RoleAttributeValueField } from "./RoleAttributeValueField";
import {
  MultiSelectAttributeValueField,
  SelectAttributeValueField,
} from "./SelectAttributeValueField";
import {
  ArrayStringAttributeValueField,
  StringAttributeValueField,
} from "./StringAttributeValueField";

import { EntryAttributeTypeTypeEnum } from "apiclient/autogenerated";

interface Props {
  control: Control<Schema>;
  setValue: UseFormSetValue<Schema>;
  type: number;
  schemaId: number;
  labelledBy?: string;
  choices?: Array<{ value?: string; label: string }>;
  isDisabled?: boolean;
}

export const AttributeValueField: FC<Props> = ({
  control,
  setValue,
  type,
  schemaId,
  labelledBy,
  choices,
  isDisabled = false,
}) => {
  switch (type) {
    case EntryAttributeTypeTypeEnum.STRING:
      return (
        <StringAttributeValueField
          labelledBy={labelledBy}
          control={control}
          attrId={schemaId}
          isDisabled={isDisabled}
        />
      );

    case EntryAttributeTypeTypeEnum.TEXT:
      return (
        <StringAttributeValueField
          labelledBy={labelledBy}
          control={control}
          attrId={schemaId}
          isDisabled={isDisabled}
          multiline
        />
      );

    case EntryAttributeTypeTypeEnum.DATE:
      return (
        <DateAttributeValueField
          attrId={schemaId}
          control={control}
          setValue={setValue}
          isDisabled={isDisabled}
        />
      );

    case EntryAttributeTypeTypeEnum.DATETIME:
      return (
        <DateTimeAttributeValueField
          attrId={schemaId}
          control={control}
          setValue={setValue}
          isDisabled={isDisabled}
        />
      );

    case EntryAttributeTypeTypeEnum.BOOLEAN:
      return (
        <BooleanAttributeValueField
          labelledBy={labelledBy}
          attrId={schemaId}
          control={control}
          isDisabled={isDisabled}
        />
      );

    case EntryAttributeTypeTypeEnum.NUMBER:
      return (
        <NumberAttributeValueField
          labelledBy={labelledBy}
          attrId={schemaId}
          control={control}
          isDisabled={isDisabled}
        />
      );

    case EntryAttributeTypeTypeEnum.OBJECT:
      return (
        <ObjectAttributeValueField
          labelledBy={labelledBy}
          attrId={schemaId}
          control={control}
          setValue={setValue}
          isDisabled={isDisabled}
        />
      );

    case EntryAttributeTypeTypeEnum.GROUP:
      return (
        <GroupAttributeValueField
          labelledBy={labelledBy}
          attrId={schemaId}
          control={control}
          setValue={setValue}
          isDisabled={isDisabled}
        />
      );

    case EntryAttributeTypeTypeEnum.ROLE:
      return (
        <RoleAttributeValueField
          labelledBy={labelledBy}
          attrId={schemaId}
          control={control}
          setValue={setValue}
          isDisabled={isDisabled}
        />
      );

    case EntryAttributeTypeTypeEnum.NAMED_OBJECT:
      return (
        <NamedObjectAttributeValueField
          labelledBy={labelledBy}
          attrId={schemaId}
          control={control}
          setValue={setValue}
          isDisabled={isDisabled}
        />
      );

    case EntryAttributeTypeTypeEnum.ARRAY_OBJECT:
      return (
        <ObjectAttributeValueField
          labelledBy={labelledBy}
          attrId={schemaId}
          control={control}
          setValue={setValue}
          isDisabled={isDisabled}
          multiple
        />
      );

    case EntryAttributeTypeTypeEnum.ARRAY_GROUP:
      return (
        <GroupAttributeValueField
          labelledBy={labelledBy}
          attrId={schemaId}
          control={control}
          setValue={setValue}
          isDisabled={isDisabled}
          multiple
        />
      );

    case EntryAttributeTypeTypeEnum.ARRAY_ROLE:
      return (
        <RoleAttributeValueField
          labelledBy={labelledBy}
          attrId={schemaId}
          control={control}
          setValue={setValue}
          isDisabled={isDisabled}
          multiple
        />
      );

    case EntryAttributeTypeTypeEnum.ARRAY_STRING:
      return (
        <ArrayStringAttributeValueField
          control={control}
          attrId={schemaId}
          labelledBy={labelledBy}
        />
      );

    case EntryAttributeTypeTypeEnum.ARRAY_NUMBER:
      return (
        <ArrayNumberAttributeValueField
          control={control}
          attrId={schemaId}
          labelledBy={labelledBy}
        />
      );

    case EntryAttributeTypeTypeEnum.ARRAY_NAMED_OBJECT:
      return (
        <ArrayNamedObjectAttributeValueField
          labelledBy={labelledBy}
          attrId={schemaId}
          control={control}
          setValue={setValue}
          isDisabled={isDisabled}
        />
      );

    case EntryAttributeTypeTypeEnum.ARRAY_NAMED_OBJECT_BOOLEAN:
      return (
        <ArrayNamedObjectAttributeValueField
          labelledBy={labelledBy}
          attrId={schemaId}
          control={control}
          setValue={setValue}
          isDisabled={isDisabled}
          withBoolean
        />
      );

    case EntryAttributeTypeTypeEnum.SELECT:
      return (
        <SelectAttributeValueField
          attrId={schemaId}
          control={control}
          choices={choices ?? []}
          isDisabled={isDisabled}
        />
      );

    case EntryAttributeTypeTypeEnum.MULTI_SELECT:
      return (
        <MultiSelectAttributeValueField
          attrId={schemaId}
          control={control}
          choices={choices ?? []}
          isDisabled={isDisabled}
        />
      );

    default:
      throw new Error(`Unknown attribute type: ${type}`);
  }
};
