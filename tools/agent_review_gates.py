"""Select existing local quality gates from Git's repository-relative paths."""

from pathlib import PurePosixPath

DJANGO_APPS = frozenset(
    {
        "acl",
        "airone",
        "api_v1",
        "category",
        "common",
        "dashboard",
        "entity",
        "entry",
        "group",
        "isolation",
        "job",
        "role",
        "trigger",
        "user",
        "webhook",
    }
)

FRONTEND_CONFIG = frozenset(
    {
        "babel.config.js",
        "biome.json",
        "eslint.config.mjs",
        "knip.jsonc",
        "openapitools.json",
        "package-lock.json",
        "package.json",
        "tsconfig.json",
        "tsconfig.lib.json",
        "tsconfig.test.json",
        "vitest.config.ts",
        "vitest.setup.i18n.ts",
        "vitest.setup.ts",
        "webpack.config.js",
        "webpack.library.config.js",
    }
)

REVIEW_TOOL_PATHS = frozenset(
    {
        "tools/agent_review.py",
        "tools/agent_review_gates.py",
        "tools/agent_review_settings.py",
        "tools/tests/test_agent_review.py",
        "tools/tests/test_agent_review_gates.py",
        "tools/tests/test_agent_review_migrations.py",
    }
)

FRONTEND_TOOLS = frozenset(
    {"tools/checkFrontendCoverageThresholds.ts", "tools/viteFrontendSrcResolver.ts"}
)


def gate_commands(paths: list[str]) -> list[list[str]]:
    """Return deterministic commands that run from the repository root."""
    commands: list[list[str]] = []
    python = False
    frontend = False
    e2e = False
    mock_browser = False
    plugin_sdk = False
    codegen = False
    review_tool = False
    apps: set[str] = set()

    for path in paths:
        if not path:
            continue
        changed = PurePosixPath(path)
        if not changed.parts or changed.suffix in {".md", ".rst"}:
            continue

        root = changed.parts[0]
        if root == "docs":
            continue
        frontend |= root == "frontend" or path in FRONTEND_CONFIG or path in FRONTEND_TOOLS
        # A view can inherit its OpenAPI schema from any runtime module,
        # including shared base classes and hooks outside the API directories.
        codegen |= (
            changed.suffix == ".py"
            and "tests" not in changed.parts
            and (root in DJANGO_APPS or root in {"api_v2", "custom_view_sample", "plugin"})
        )
        codegen |= path in {
            "manage.py",
            "pyproject.toml",
            "uv.lock",
            "package.json",
            "package-lock.json",
            "tools/generate_client.sh",
            "openapitools.json",
            "tools/check_generated_client.sh",
        } or path.startswith("frontend/src/apiclient/autogenerated/")
        e2e |= root == "e2e"
        mock_browser |= root == "e2e" and changed.parts[:2] != ("e2e", "live")
        plugin_sdk |= changed.parts[:2] == ("plugin", "sdk")
        python |= changed.suffix == ".py" or path in {"pyproject.toml", "uv.lock"}

        if root in DJANGO_APPS:
            apps.add(root)
        elif root == "custom_view_sample":
            apps.add("custom_view")
        elif root in {"api_v2", "plugin"} and changed.parts[:3] != ("plugin", "sdk", "tests"):
            apps.add("airone")
        elif changed.parts[:2] == ("templates", "registration") or path.startswith(
            "templates/password_reset"
        ):
            apps.add("airone")
        elif root in {"templates", "static"}:
            apps.add("entry")
        elif path in REVIEW_TOOL_PATHS:
            review_tool = True
        elif root == "tools" and changed.suffix == ".py":
            apps.add("tools")
        elif path in {
            "manage.py",
            "pyproject.toml",
            "uv.lock",
            "tools/lite.sh",
            "tools/test_local.sh",
        }:
            apps.update({"airone", "entry"})

    if codegen:
        commands.append(["tools/check_generated_client.sh"])
    if python:
        # CI installs custom_view before running Ruff. Match its import classification
        # in a fresh linked checkout, where only custom_view_sample is present.
        commands.extend(
            [
                [
                    "uv",
                    "run",
                    "ruff",
                    "check",
                    "--config",
                    'lint.isort.known-first-party=["custom_view"]',
                    ".",
                ],
                ["uv", "run", "ruff", "format", "--check", "."],
            ]
        )
    if review_tool:
        commands.append(
            ["uv", "run", "python", "-m", "unittest", "tools.tests.test_agent_review_migrations"]
        )
        commands.append(
            [
                "python3",
                "-m",
                "unittest",
                "tools.tests.test_agent_review",
                "tools.tests.test_agent_review_gates",
            ]
        )
    if plugin_sdk:
        commands.append(["tools/lite.sh", "test", "plugin.sdk.tests"])
    # App-level test processes isolate global state in Django and plugin registries.
    commands.extend(["tools/lite.sh", "test", app] for app in sorted(apps))
    if frontend or e2e:
        commands.extend([["npm", "run", "lint"], ["npm", "run", "typecheck"]])
    if frontend:
        commands.append(["npm", "run", "test"])
    if mock_browser:
        commands.extend(
            [
                ["npm", "run", "build"],
                [
                    "env",
                    "CI=1",
                    "npm",
                    "exec",
                    "--offline",
                    "--",
                    "playwright",
                    "test",
                    "--config=e2e/playwright.config.ts",
                ],
            ]
        )
    return commands
