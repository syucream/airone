import unittest

from tools.agent_review_gates import gate_commands


class GateCommandsTest(unittest.TestCase):
    def test_docs_and_unknown_non_code_only_use_callers_whitespace_check(self):
        self.assertEqual(
            gate_commands(
                ["README.md", "docs/examples/sample.py", "frontend/README.md", "LICENSE"]
            ),
            [],
        )

    def test_django_apps_run_in_separate_processes_in_stable_order(self):
        paths = ["entry/deleted.py", "entity/tasks.py", "entry/tests/new.py"]
        commands = gate_commands(paths)
        self.assertEqual(commands, gate_commands(list(reversed(paths))))
        self.assertEqual(
            commands,
            [
                ["tools/check_generated_client.sh"],
                [
                    "uv",
                    "run",
                    "ruff",
                    "check",
                    "--config",
                    'lint.isort.known-first-party=["custom_view"]',
                    ".",
                ],
                ["uv", "run", "ruff", "format", "--check", "."],
                ["tools/lite.sh", "test", "entity"],
                ["tools/lite.sh", "test", "entry"],
            ],
        )

    def test_review_harness_changes_select_both_unittest_modules(self):
        for path in (
            "tools/agent_review.py",
            "tools/agent_review_gates.py",
            "tools/tests/test_agent_review.py",
            "tools/tests/test_agent_review_gates.py",
        ):
            with self.subTest(path=path):
                commands = gate_commands([path])
                self.assertEqual(
                    commands[-1],
                    [
                        "python3",
                        "-m",
                        "unittest",
                        "tools.tests.test_agent_review",
                        "tools.tests.test_agent_review_gates",
                    ],
                )

    def test_existing_django_tool_tests_use_lite(self):
        self.assertEqual(
            gate_commands(["tools/update_es_document.py"])[-1],
            ["tools/lite.sh", "test", "tools"],
        )

    def test_unknown_python_uses_ruff_without_guessing_an_app_name(self):
        self.assertEqual(
            gate_commands(["unknown/deleted.py"]),
            [
                [
                    "uv",
                    "run",
                    "ruff",
                    "check",
                    "--config",
                    'lint.isort.known-first-party=["custom_view"]',
                    ".",
                ],
                ["uv", "run", "ruff", "format", "--check", "."],
            ],
        )

    def test_frontend_sources_and_build_configuration_use_frontend_commands(self):
        self.assertEqual(
            gate_commands(["frontend/src/deleted.ts", "tsconfig.json"]),
            [["npm", "run", "lint"], ["npm", "run", "typecheck"], ["npm", "run", "test"]],
        )

    def test_mock_e2e_uses_static_checks_bundle_and_playwright(self):
        self.assertEqual(
            gate_commands(["e2e/entries.spec.ts"]),
            [
                ["npm", "run", "lint"],
                ["npm", "run", "typecheck"],
                ["npm", "run", "build"],
                [
                    "env",
                    "CI=1",
                    "npm",
                    "exec",
                    "--offline",
                    "--",
                    "playwright",
                    "test",
                    "--config=e2e/playwright.config.ts",
                ],
            ],
        )

    def test_live_e2e_only_uses_frontend_static_checks(self):
        self.assertEqual(
            gate_commands(["e2e/live/entry.live-spec.ts"]),
            [["npm", "run", "lint"], ["npm", "run", "typecheck"]],
        )

    def test_plugin_sdk_runs_standalone_tests_and_django_integration(self):
        commands = gate_commands(["plugin/sdk/pagoda_plugin_sdk/api/base.py"])
        self.assertIn(["tools/lite.sh", "test", "plugin.sdk.tests"], commands)
        self.assertEqual(commands[-1], ["tools/lite.sh", "test", "airone"])

    def test_sample_exercises_its_own_installed_app(self):
        self.assertIn(
            ["tools/lite.sh", "test", "custom_view"],
            gate_commands(["custom_view_sample/api_v2/views.py"]),
        )

    def test_login_template_runs_auth_tests(self):
        self.assertIn(
            ["tools/lite.sh", "test", "airone"],
            gate_commands(["templates/registration/login.html"]),
        )

    def test_codegen_inputs_regenerate_and_compare_to_committed_client(self):
        for path in (
            "tools/generate_client.sh",
            "openapitools.json",
            "package-lock.json",
            "uv.lock",
            "airone/lib/configuration_export.py",
            "airone/spectacular.py",
            "entry/api_v2/views.py",
            "entity/models.py",
            "frontend/src/apiclient/autogenerated/apis/EntryApi.ts",
        ):
            with self.subTest(path=path):
                self.assertIn(["tools/check_generated_client.sh"], gate_commands([path]))

    def test_backend_tests_alone_do_not_regenerate_the_client(self):
        self.assertNotIn(
            ["tools/check_generated_client.sh"], gate_commands(["airone/tests/test_export.py"])
        )
